import { chromium } from '@playwright/test';
import fs from 'node:fs';
const token = fs.readFileSync('/tmp/wr-token.txt','utf8').trim();
const email = fs.readFileSync('/tmp/wr-email.txt','utf8').trim();
const U={id:11001,name:'QA Music',email,role:'user',status:'active',jobTitle:'Editor',department:'Media & Content',teamId:null,avatarData:null};
const b=await chromium.launch(); const c=await b.newContext({viewport:{width:1440,height:950}}); const p=await c.newPage();
await p.route('**/api/auth/me',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({user:U})}));
await p.goto('http://localhost:5173',{waitUntil:'domcontentloaded'});
await p.evaluate(([t,e])=>{localStorage.setItem('token',t);localStorage.setItem('workrank_active_user_id','11001');localStorage.setItem('workrank_user_email',e);},[token,email]);
await p.goto('http://localhost:5173/games/typing/music',{waitUntil:'domcontentloaded'});
await p.waitForSelector('.music-song-card');
await p.getByRole('tab',{name:'Bảng xếp hạng'}).click();
await p.waitForSelector('.music-board');
await p.waitForTimeout(600);
console.log(await p.evaluate(()=>document.querySelector('.music-board')?.innerText.replace(/\n+/g,' | ').slice(0,300)));
await p.screenshot({path:'/tmp/music-08-board.png'});
await b.close();
