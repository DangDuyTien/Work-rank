'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { User, TypingRoom, TypingPlayer, TypingMatchResult, ScoreLedger } = require('../src/models');
const game = require('../src/services/typingGame.service');
test('Arcade TRIO: capacity, readiness, 3s countdown, authoritative winner and replay in the same room', async () => {
  const users = await Promise.all([0,1,2,3].map(n => User.create({ name:`Trio ${n}`, email:`trio-${n}@audit.test`, passwordHash:'hash', status:'active', role:'user' })));
  const initial = await game.createRoom({ mode:'TRIO', durationLimitSeconds:30, matchType:'RANKED' }, users[0]);
  const id = initial.room.id;
  assert.equal(initial.room.mode,'TRIO'); assert.equal(initial.room.maxPlayers,3);
  await game.joinRoom(id,users[1].id);
  await assert.rejects(game.startMatch(id,users[0].id));
  await game.joinRoom(id,users[2].id); await assert.rejects(game.joinRoom(id,users[3].id));
  for (const u of users.slice(0,3)) await game.toggleReady(id,u.id,true);
  const ready = await game.getRoomDetail(id,users[0].id);
  assert.equal(ready.room.status,'STARTING'); assert.ok(new Date(ready.room.startAt)-Date.now()<=3300);
  await assert.rejects(game.startMatch(id,users[1].id));
  await game.startMatch(id,users[0].id);
  await assert.rejects(game.resetRoom(id,users[0].id));
  await TypingRoom.update({startedAt:new Date(Date.now()-21000)},{where:{id}});
  for (let i=0;i<3;i++) await game.submitFinish(id,users[i].id,{typedText:Array.from(initial.room.challengeText).slice(0,80-i*10).join(''),inputRevision:1});
  const done = await game.getRoomDetail(id,users[0].id);
  assert.equal(done.room.status,'FINISHED'); assert.equal(Number(done.room.winnerUserId),Number(users[0].id));
  assert.deepEqual(done.result.results.map(p=>p.individualRank).sort(),[1,2,3]);
  const awards=await ScoreLedger.count(); assert.ok(awards>0);
  await game.submitFinish(id,users[0].id,{typedText:'forged',inputRevision:99}); assert.equal(await ScoreLedger.count(),awards);
  const resets=await Promise.allSettled([game.resetRoom(id,users[0].id),game.resetRoom(id,users[0].id)]);
  assert.equal(resets.filter(r=>r.status==='fulfilled').length,1);
  const next=await game.getRoomDetail(id,users[0].id);
  assert.equal(next.room.status,'WAITING'); assert.equal(next.players.length,3); assert.equal(next.result,null);
  assert.ok(next.players.every(p=>!p.isReady)); assert.equal(await TypingMatchResult.count({where:{roomId:id}}),1);
  const history=await game.getHistory(users[0].id);
  const saved=history.attempts.find(a=>Number(a.roomId)===Number(id));
  assert.ok(saved?.validatedAt&&saved?.createdAt&&saved?.startedAt);
  assert.equal(saved.gameType,'typing_battle');assert.equal(saved.rank,1);
  assert.equal(saved.score,done.result.results.find(r=>r.userId===users[0].id).performanceScore);
  assert.equal(await ScoreLedger.count(),awards);
  for(const u of users.slice(0,3)) await game.leaveRoom(id,u.id);
  assert.equal(await TypingPlayer.count({where:{roomId:id}}),0);
});
